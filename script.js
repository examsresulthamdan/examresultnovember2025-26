let selectedClassKey = null;
let selectedStudentName = null;

function sanitizeForFilename(name) {
  return name.trim().toLowerCase().replace(/[^a-z0-9Ā-ſ]+/g, "_").replace(/^_+|_+$/g, "");
}

function renderClassButtons() {
  const container = document.getElementById('classContainer');
  container.innerHTML = '';
  classes.forEach(c => {
    const btn = document.createElement('button');
    btn.className = 'class-btn';
    btn.innerText = c.name;
    btn.onclick = () => openClass(c.key);
    container.appendChild(btn);
  });
}

function openClass(classKey) {
  selectedClassKey = classKey;
  document.getElementById('classTitle').innerText = classes.find(c => c.key === classKey).name;
  const studentList = document.getElementById('studentList');
  studentList.innerHTML = '';
  const students = data[classKey].students || { };
  const names = Object.keys(students).sort((a,b) => a.localeCompare(b));
  if (names.length === 0) {
    const p = document.createElement('p');
    p.innerText = "No students found for this class.";
    studentList.appendChild(p);
  } else {
    names.forEach(student => {
      const btn = document.createElement('button');
      btn.innerText = student;
      btn.onclick = () => openPasswordPopup(student);
      studentList.appendChild(btn);
    });
  }
  document.getElementById('studentPopup').style.display = 'flex';
}

function openPasswordPopup(studentName) {
  selectedStudentName = studentName;
  document.getElementById('studentNameTitle').innerText = studentName;
  document.getElementById('passwordInput').value = '';
  document.getElementById('passwordPopup').style.display = 'flex';
}

function verifyPassword() {
  const entered = document.getElementById('passwordInput').value.trim();
  const student = data[selectedClassKey].students[selectedStudentName];
  if (!student) { alert("Student data not found."); return; }
  const correct = String(student.password || "");
  if (entered === correct) {
    let imgPath = student.image;
    if (!imgPath) imgPath = 'results/' + selectedClassKey + '/' + sanitizeForFilename(selectedStudentName) + '.jpg';
    const imgEl = document.getElementById('resultImage');
    imgEl.src = imgPath;
    imgEl.onerror = function() { this.src = ''; alert('Result image not found at: ' + imgPath + '\n\nPlease check that the image file exists and path is correct.'); };
    document.getElementById('resultPopup').style.display = 'flex';
    closePopup('passwordPopup');
  } else { alert('Incorrect Password!'); }
}

function closePopup(id) { document.getElementById(id).style.display = 'none'; }

function downloadImage() { const img = document.getElementById('resultImage'); if (!img || !img.src) { alert('No image to download'); return; } const link = document.createElement('a'); link.href = img.src; const filename = sanitizeForFilename(selectedStudentName || 'result') + '_result.jpg'; link.download = filename; link.click(); }

